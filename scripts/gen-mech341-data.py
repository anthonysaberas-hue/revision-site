"""Generate property tables for the MECH 341 lib (run once; output is committed).

Water and R-134a from CoolProp (IAPWS-95 / Tillner-Roth), R-134a shifted to the ASHRAE reference used by
Cengel (h = s = 0 for saturated liquid at -40 C). Ideal-gas data from the NASA 9-coefficient polynomials
shipped with Cantera (nasa_gas.yaml, 200-6000 K, JANAF-consistent).
Usage: python -I scripts/gen-mech341-data.py   (from the repo root)
"""
import math, os, json
from CoolProp.CoolProp import PropsSI as PS
import cantera as ct

OUT = os.path.join(os.path.dirname(__file__), '..', 'src', 'courses', 'mech341', 'lib', 'data')
os.makedirs(OUT, exist_ok=True)

def r(v, d=5):
    if v == 0 or not math.isfinite(v):
        return 0
    return float(f'{v:.{d}g}')

def dump(name, obj, comment):
    path = os.path.join(OUT, name + '.ts')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('// AUTO-GENERATED by scripts/gen-mech341-data.py — do not edit.\n// ' + comment + '\n')
        for k, v in obj.items():
            f.write(f'export const {k} = {json.dumps(v, separators=(",", ":"))};\n')
    print(path, os.path.getsize(path))

# ---------------------------------------------------------------- pure fluids
def fluid_tables(fl, Tmin, Tmax, Tstep, hoff=0.0, soff=0.0, Pmax_sup=60000, Tsup_max=1300, prows=None):
    Tc = PS('Tcrit', fl) - 273.15
    Pc = PS('pcrit', fl) / 1e3
    Ts = []
    t = Tmin
    while t < Tc - 0.5:
        Ts.append(round(t, 3))
        t += Tstep
    for t in [Tc - 0.5, Tc - 0.2, Tc - 0.05]:
        Ts.append(round(t, 3))
    sat = {k: [] for k in ['T', 'P', 'vf', 'vg', 'uf', 'ug', 'hf', 'hg', 'sf', 'sg']}
    for t in Ts:
        T = t + 273.15
        sat['T'].append(t)
        sat['P'].append(r(PS('P', 'T', T, 'Q', 0, fl) / 1e3, 6))
        for q, sfx in [(0, 'f'), (1, 'g')]:
            sat['v' + sfx].append(r(1 / PS('D', 'T', T, 'Q', q, fl), 6))
            sat['u' + sfx].append(r(PS('U', 'T', T, 'Q', q, fl) / 1e3 - hoff, 6))
            sat['h' + sfx].append(r(PS('H', 'T', T, 'Q', q, fl) / 1e3 - hoff, 6))
            sat['s' + sfx].append(r(PS('S', 'T', T, 'Q', q, fl) / 1e3 - soff, 6))
    # superheated rows: superheat offsets above Tsat(P)
    dTs = [0, 1, 2.5, 5, 7.5, 10, 15, 20, 30, 40, 50, 60, 80, 100, 125, 150, 175, 200, 250, 300, 350, 400, 450, 500, 600, 700, 800, 900, 1000, 1100, 1200]
    sup = {'P': [], 'Tsat': [], 'dT': dTs, 'h': [], 's': [], 'v': []}
    for P in prows:
        if P >= Pc:
            continue
        Tsat = PS('T', 'P', P * 1e3, 'Q', 1, fl)
        hr, sr, vr = [], [], []
        for d in dTs:
            T = Tsat + d
            if T - 273.15 > Tsup_max:
                break
            if d == 0:
                hh = PS('H', 'P', P * 1e3, 'Q', 1, fl); ss = PS('S', 'P', P * 1e3, 'Q', 1, fl); dd = PS('D', 'P', P * 1e3, 'Q', 1, fl)
            else:
                hh = PS('H', 'P', P * 1e3, 'T', T, fl); ss = PS('S', 'P', P * 1e3, 'T', T, fl); dd = PS('D', 'P', P * 1e3, 'T', T, fl)
            hr.append(r(hh / 1e3 - hoff, 6)); sr.append(r(ss / 1e3 - soff, 6)); vr.append(r(1 / dd, 5))
        sup['P'].append(P); sup['Tsat'].append(r(Tsat - 273.15, 6)); sup['h'].append(hr); sup['s'].append(sr); sup['v'].append(vr)
    return sat, sup, Tc, Pc

# water: Cengel-like pressures plus a log fill
wp = sorted(set([0.6117, 1, 1.5, 2, 3, 4, 5, 7.5, 10, 15, 20, 25, 30, 40, 50, 75, 100, 125, 150, 175, 200, 250, 300, 350, 400, 450, 500, 600, 700, 800, 900,
                 1000, 1200, 1400, 1600, 1800, 2000, 2500, 3000, 3500, 4000, 4500, 5000, 6000, 7000, 8000, 9000, 10000, 11000, 12500, 14000, 15000,
                 16000, 17500, 18500, 20000, 21000, 22000]))
wsat, wsup, wTc, wPc = fluid_tables('Water', 0.01, 374, 1.0, prows=wp)
wsat['T'][0] = 0.01
# supercritical rows (T based)
sc = {'P': [22064.0001, 25000, 30000, 35000, 40000, 50000, 60000], 'T': [], 'h': [], 's': [], 'v': []}
Tgrid = list(range(0, 360, 10)) + list(range(360, 460, 2)) + list(range(460, 1301, 10))
sc['T'] = Tgrid
sc['P'][0] = 22100
for P in sc['P']:
    sc['h'].append([r(PS('H', 'P', P * 1e3, 'T', t + 273.15, 'Water') / 1e3, 6) for t in Tgrid])
    sc['s'].append([r(PS('S', 'P', P * 1e3, 'T', t + 273.15, 'Water') / 1e3, 6) for t in Tgrid])
    sc['v'].append([r(1 / PS('D', 'P', P * 1e3, 'T', t + 273.15, 'Water'), 5) for t in Tgrid])
dump('water', {'WSAT': wsat, 'WSUP': wsup, 'WSC': sc, 'W_CRIT': {'T': r(wTc, 6), 'P': r(wPc, 6)}},
     'Water (IAPWS-95 via CoolProp). Saturation by T (C, kPa, m3/kg, kJ/kg, kJ/kgK); superheated rows indexed by superheat dT above Tsat(P); supercritical rows by T.')

# R-134a, ASHRAE reference: h = s = 0 for saturated liquid at -40 C
hoff = PS('H', 'T', 233.15, 'Q', 0, 'R134a') / 1e3
soff = PS('S', 'T', 233.15, 'Q', 0, 'R134a') / 1e3
rp = [51.25, 60, 70, 80, 90, 100, 120, 140, 160, 180, 200, 240, 280, 320, 360, 400, 450, 500, 550, 600, 700, 800, 900, 1000, 1200, 1400, 1600, 1800, 2000, 2400, 2800, 3200, 3600, 4000]
rsat, rsup, rTc, rPc = fluid_tables('R134a', -40, 101, 1.0, hoff, soff, Tsup_max=200, prows=rp)
dump('r134a', {'RSAT': rsat, 'RSUP': rsup, 'R_CRIT': {'T': r(rTc, 6), 'P': r(rPc, 6)}},
     'R-134a (CoolProp) shifted to the ASHRAE reference of Cengel (h = s = 0, saturated liquid at -40 C).')

# ---------------------------------------------------------------- ideal gases (NASA-9)
SP = {s.name: s for s in ct.Species.list_from_file('nasa_gas.yaml')}
names = ['N2', 'O2', 'CO2', 'CO', 'H2O', 'H2', 'O', 'OH', 'NO', 'N', 'H', 'Ar']
Tg = [200, 220, 240, 260, 280, 298.15, 300] + list(range(320, 1000, 20)) + list(range(1000, 3000, 20)) + list(range(3000, 6001, 50))
gas = {'T': Tg}
for n in names:
    t = SP[n].thermo
    gas[n] = {
        'h298': r(t.h(298.15) / 1e3, 7),
        'dh': [r(t.h(T) / 1e3 - t.h(298.15) / 1e3, 7) for T in Tg],   # kJ/kmol sensible from 298.15 K
        's0': [r(t.s(T) / 1e3, 7) for T in Tg],                          # kJ/kmol K at 1 atm (101.325 kPa)
    }
# air (dry) as a mixture: N2 .7808, O2 .2095, Ar .0093, CO2 .0004 -> per kg, Cengel A-17 conventions
yA = {'N2': 0.78084, 'O2': 0.20946, 'Ar': 0.00934, 'CO2': 0.00036}
Mair = 28.9647
Ra = 8.31447 / Mair
Ta = list(range(200, 3001, 10))
hA = [sum(y * (SP[n].thermo.h(T) - SP[n].thermo.h(298.15)) for n, y in yA.items()) / 1e3 / Mair for T in Ta]
s0A = [sum(y * SP[n].thermo.s(T) for n, y in yA.items()) / 1e3 / Mair for T in Ta]   # pure-component s at 1 atm (mixing term constant)
i300 = Ta.index(300)
hshift = 300.19 - hA[i300]
sshift = 1.70203 - s0A[i300]
air = {'T': Ta, 'h': [r(h + hshift, 6) for h in hA], 's0': [r(s + sshift, 6) for s in s0A]}
air['u'] = [r(air['h'][i] - Ra * T, 6) for i, T in enumerate(Ta)]
air['Pr'] = [r(1.3860 * math.exp((s - air['s0'][i300]) / Ra), 6) for s in air['s0']]
air['vr'] = [r(621.2 * (T / 300) / (air['Pr'][i] / 1.3860), 6) for i, T in enumerate(Ta)]
dump('gases', {'GAS': gas, 'AIRT': air, 'AIR_M': Mair},
     'Ideal-gas data from NASA 9-coefficient polynomials (Cantera nasa_gas.yaml). GAS[sp].dh = h(T) - h(298.15) kJ/kmol, s0 at 1 atm; AIRT per kg in Cengel A-17 convention (h(300)=300.19, s0(300)=1.70203, Pr(300)=1.386).')
